CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id bigint,p_as_of date)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due date; v_return date; v_end date;
BEGIN
 SELECT due_on,returned_on INTO v_due,v_return FROM loans WHERE loan_id=p_loan_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date is required'; END IF;
 v_end:=LEAST(p_as_of,COALESCE(v_return,p_as_of));
 RETURN GREATEST(v_end-v_due,0)*2.00;
END $$;

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id bigint,p_returned_on date)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed date; v_due date;
BEGIN
 IF p_returned_on IS NULL THEN RAISE EXCEPTION 'Return date is required'; END IF;
 SELECT borrowed_on,due_on INTO v_borrowed,v_due FROM loans WHERE loan_id=p_loan_id AND returned_on IS NULL FOR UPDATE;
 IF NOT FOUND THEN
   IF NOT EXISTS(SELECT 1 FROM loans WHERE loan_id=p_loan_id) THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id;
   ELSE RAISE EXCEPTION 'Loan % has already been returned',p_loan_id; END IF;
 END IF;
 IF p_returned_on<v_borrowed THEN RAISE EXCEPTION 'Return date cannot precede borrowing date'; END IF;
 UPDATE loans SET returned_on=p_returned_on,
 fine_amount=GREATEST(p_returned_on-due_on,0)*2.00 WHERE loan_id=p_loan_id;
END $$;

CREATE OR REPLACE FUNCTION trg_loan_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
  INSERT INTO loan_audit(loan_id,old_returned_on,new_returned_on)
  VALUES(NEW.loan_id,OLD.returned_on,NEW.returned_on);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER loans_return_audit AFTER UPDATE ON loans
FOR EACH ROW EXECUTE FUNCTION trg_loan_audit_fn();

CREATE OR REPLACE VIEW v_overdue_loans AS
SELECT l.loan_id,b.title,l.borrower_name,l.due_on,fn_loan_fine(l.loan_id,CURRENT_DATE) AS fine_as_of_today
FROM loans l JOIN books b USING(book_id)
WHERE l.returned_on IS NULL AND l.due_on<CURRENT_DATE;

CREATE INDEX idx_loans_unreturned_book ON loans(book_id) WHERE returned_on IS NULL;
EXPLAIN SELECT * FROM loans WHERE book_id=1 AND returned_on IS NULL;

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of date)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'Snapshot date is required'; END IF;
 INSERT INTO overdue_summary(snapshot_date,overdue_count,total_fine)
 SELECT p_as_of,count(*) FILTER(WHERE returned_on IS NULL AND due_on<p_as_of),
 COALESCE(sum(GREATEST(p_as_of-due_on,0)*2.00) FILTER(WHERE returned_on IS NULL),0)
 FROM loans
 ON CONFLICT(snapshot_date) DO UPDATE
 SET overdue_count=EXCLUDED.overdue_count,total_fine=EXCLUDED.total_fine;
END $$;